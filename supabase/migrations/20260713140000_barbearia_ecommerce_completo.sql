-- E-commerce multi-tenant da barbearia: pedidos, cupons, estoque reservado e carrinhos recuperaveis.

alter table public.barbearia_produtos
  add column if not exists estoque_reservado numeric(12,3) not null default 0 check (estoque_reservado >= 0);

create table public.barbearia_cupons (
  id uuid primary key default gen_random_uuid(),
  barbearia_id uuid not null references public.barbearias(id) on delete cascade,
  codigo text not null,
  descricao text,
  tipo text not null check (tipo in ('percentual', 'fixo')),
  valor numeric(12,2) not null check (valor > 0),
  pedido_minimo numeric(12,2) not null default 0 check (pedido_minimo >= 0),
  desconto_maximo numeric(12,2) check (desconto_maximo is null or desconto_maximo > 0),
  limite_usos integer check (limite_usos is null or limite_usos > 0),
  usos integer not null default 0 check (usos >= 0),
  inicia_em timestamptz,
  termina_em timestamptz,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (barbearia_id, id)
);

create unique index barbearia_cupons_codigo_idx
  on public.barbearia_cupons (barbearia_id, lower(codigo));
create index barbearia_cupons_validade_idx
  on public.barbearia_cupons (barbearia_id, ativo, termina_em);

