    'enviado', 'concluido', 'cancelado', 'estornado'
  )),
  pagamento_status text not null default 'pendente' check (pagamento_status in (
    'pendente', 'pago', 'falhou', 'cancelado', 'estornado', 'pagar_na_retirada'
  )),
  entrega_tipo text not null default 'retirada' check (entrega_tipo in ('retirada', 'entrega')),
  nome_cliente text not null,
  telefone_cliente text not null,
  email_cliente text,
  cpf_cliente text,
  cep text,
  endereco text,
  numero_endereco text,
  complemento text,
  bairro text,
  cidade text,
  estado text,
  referencia_entrega text,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  desconto numeric(12,2) not null default 0 check (desconto >= 0),
  frete numeric(12,2) not null default 0 check (frete >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
